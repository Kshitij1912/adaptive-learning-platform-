"""Generate a DEV STAND-IN dataset in the exact OULAD CSV format.

The real OULAD (https://analytics.open.ac.uk/oulad, CC BY 4.0) has to be downloaded manually.
This generator exists only so the pipeline, API and tests run end-to-end without it.
Models trained on it are tagged trained_on="dev_standin" and their metrics mean nothing.

    python -m scripts.make_dev_oulad --out data/dev_oulad --n 3000
"""
import argparse
from pathlib import Path

import numpy as np
import pandas as pd

MODULE, PRES = "AAA", "2013J"
ASSESS_DAYS = [21, 42, 70, 98, 126, 154, 196, 238]


def generate(out: str | Path, n: int = 3000, seed: int = 7) -> None:
    out = Path(out)
    out.mkdir(parents=True, exist_ok=True)
    rng = np.random.default_rng(seed)
    ability = rng.beta(4, 3, n)
    e0 = rng.beta(3, 3, n)
    withdraw_week = np.full(n, 99)
    for i in range(n):
        for w in range(39):
            if rng.random() < 0.01 + 0.07 * (1 - e0[i]) ** 2:
                withdraw_week[i] = w
                break
    ids = np.arange(100000, 100000 + n)

    vle_rows = []
    for i in range(n):
        for w in range(39):
            if w >= withdraw_week[i]:
                break
            e = e0[i] * (0.995 ** w)
            if rng.random() < 0.10 + 0.90 * e:
                total = max(1, rng.poisson(e * 80))
                for d in rng.choice(7, size=rng.integers(1, 4), replace=False):
                    vle_rows.append((MODULE, PRES, ids[i], int(rng.integers(1, 40)), w * 7 + int(d),
                                     max(1, total // 2)))
    pd.DataFrame(vle_rows, columns=["code_module", "code_presentation", "id_student", "id_site",
                                    "date", "sum_click"]).to_csv(out / "studentVle.csv", index=False)

    asm = pd.DataFrame({
        "code_module": MODULE, "code_presentation": PRES, "id_assessment": range(1, len(ASSESS_DAYS) + 1),
        "assessment_type": ["TMA"] * 7 + ["Exam"], "date": ASSESS_DAYS, "weight": [10] * 7 + [30],
    })
    asm.to_csv(out / "assessments.csv", index=False)

    sa_rows, final = [], []
    for i in range(n):
        scores = []
        for aid, day in enumerate(ASSESS_DAYS, start=1):
            if day // 7 >= withdraw_week[i] or rng.random() > 0.35 + 0.65 * e0[i]:
                continue
            sc = float(np.clip(100 * (ability[i] + rng.normal(0, 0.10)), 0, 100))
            scores.append(sc)
            sa_rows.append((aid, ids[i], max(0, day + int(rng.integers(-3, 3))), 0, round(sc, 1)))
        if withdraw_week[i] < 99:
            final.append("Withdrawn")
        else:
            v = 0.8 * ability[i] + 0.2 * e0[i] + rng.normal(0, 0.05)
            final.append("Distinction" if v >= 0.72 else "Pass" if v >= 0.45 else "Fail")
    pd.DataFrame(sa_rows, columns=["id_assessment", "id_student", "date_submitted", "is_banked", "score"]) \
        .to_csv(out / "studentAssessment.csv", index=False)

    pd.DataFrame({
        "code_module": MODULE, "code_presentation": PRES, "id_student": ids,
        "gender": rng.choice(["M", "F"], n), "region": "Unknown", "highest_education": "A Level or Equivalent",
        "imd_band": "50-60%", "age_band": rng.choice(["0-35", "35-55", "55<="], n),
        "num_of_prev_attempts": 0, "studied_credits": 60, "disability": "N", "final_result": final,
    }).to_csv(out / "studentInfo.csv", index=False)

    (out / "DEV_STANDIN.txt").write_text(
        "Generated by scripts/make_dev_oulad.py. NOT real OULAD data. Replace with the real CSVs.\n")


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default="data/dev_oulad")
    ap.add_argument("--n", type=int, default=3000)
    ap.add_argument("--seed", type=int, default=7)
    a = ap.parse_args()
    generate(a.out, a.n, a.seed)
    print(f"wrote dev stand-in OULAD-format data to {a.out}")
